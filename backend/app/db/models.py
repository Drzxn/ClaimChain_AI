        CheckConstraint("quote_start >= 0", name="ck_passages_quote_start"),
        CheckConstraint("quote_end >= quote_start", name="ck_passages_quote_range"),
        CheckConstraint("token_count > 0", name="ck_passages_token_count"),
        UniqueConstraint("source_id", "chunk_index", name="uq_passages_source_chunk"),
        Index("ix_passages_source", "source_id"),
