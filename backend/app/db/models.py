"""ORM models for the eight core ClaimChain tables.

Schema source of truth: the approved technical specification, Â§3.

Design notes
------------
* All primary keys are ``uuid`` with a server-side ``gen_random_uuid()``
  default, so a row is valid even when inserted outside SQLAlchemy.
* All timestamps are ``timestamptz`` (timezone-aware), never naive.
* Enum-like columns are ``text`` with a CHECK constraint rather than native
  PostgreSQL enums. Adding a value later is a constraint swap, not a type
  migration, and the values stay readable in the database.
* Scores are ``numeric`` with explicit CHECK bounds. Floats would let a bug
  write ``1.0000000001`` and silently pass a ``<= 1`` test.
* ``runs.stage`` stores the conceptual stage number (1-6). Runtime execution
  order is 1 -> 2 -> 3 -> 5 -> 4 -> 6 and is *not* encoded here; ordering is
  the orchestrator's job and the run log records actual timestamps.
"""

from __future__ import annotations

import uuid
from datetime import date, datetime
from decimal import Decimal
from typing import Any

from sqlalchemy import (
    Boolean,
    CheckConstraint,
    Date,
    DateTime,
    ForeignKey,
    Index,
    Integer,
    Numeric,
    String,
    Text,
    UniqueConstraint,
    func,
)
from sqlalchemy import text as sa_text
from sqlalchemy.dialects.postgresql import JSONB, UUID
from sqlalchemy.orm import Mapped, mapped_column
from sqlalchemy.orm import relationship as orm_relationship

from app.db.base import Base

# ---------------------------------------------------------------------------
# Shared column helpers
# ---------------------------------------------------------------------------

def _uuid_pk() -> Mapped[uuid.UUID]:
    """UUID primary key, generated by PostgreSQL."""
    return mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        server_default=sa_text("gen_random_uuid()"),
    )


def _created_at() -> Mapped[datetime]:
    """Timezone-aware creation timestamp, defaulted by the database."""
    return mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now()
    )


# ---------------------------------------------------------------------------
# Enum-like value sets (mirrored in CHECK constraints below)
# ---------------------------------------------------------------------------

CLAIM_DOMAINS = ("technology", "science", "general")
CLAIM_STATUSES = ("queued", "running", "complete", "failed")
CLAIM_TYPES = ("factual", "causal", "comparative", "definitional", "quantitative")
SOURCE_TYPES = ("primary", "secondary", "reference", "news", "opinion", "unknown")
RELATIONSHIPS = ("SUPPORTS", "CONTRADICTS", "MIXED", "INSUFFICIENT")
SUB_VERDICTS = ("SUPPORTED", "CONTRADICTED", "MIXED", "INSUFFICIENT")
OVERALL_VERDICTS = (
    "SUPPORTED",
    "CONTRADICTED",
    "MIXED",
    "INSUFFICIENT_EVIDENCE",
    "MISLEADING",
)
RUN_STATUSES = ("running", "complete", "failed", "skipped")
QUOTE_VALIDATION_STATES = ("passed", "failed")


def _in_clause(column: str, values: tuple[str, ...]) -> str:
    """Render a SQL ``IN`` list for a CHECK constraint."""
    joined = ", ".join(f"'{v}'" for v in values)
    return f"{column} IN ({joined})"


