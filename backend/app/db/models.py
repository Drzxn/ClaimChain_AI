class Claim(Base):
    """A user-submitted statement awaiting decomposition and verification."""

    __tablename__ = "claims"
    __table_args__ = (
        CheckConstraint(
            "char_length(raw_text) BETWEEN 1 AND 2000",
            name="ck_claims_raw_text_length",
        ),
        CheckConstraint(_in_clause("domain", CLAIM_DOMAINS), name="ck_claims_domain"),
        CheckConstraint(_in_clause("status", CLAIM_STATUSES), name="ck_claims_status"),
        Index("ix_claims_status_created", "status", sa_text("created_at DESC")),
    )

    id: Mapped[uuid.UUID] = _uuid_pk()
    raw_text: Mapped[str] = mapped_column(Text, nullable=False)
    domain: Mapped[str] = mapped_column(
        Text, nullable=False, server_default=sa_text("'general'")
    )
    status: Mapped[str] = mapped_column(
        Text, nullable=False, server_default=sa_text("'queued'")
    )
    model_config: Mapped[dict[str, Any]] = mapped_column(
        JSONB, nullable=False, server_default=sa_text("'{}'::jsonb")
    )
    error: Mapped[str | None] = mapped_column(Text, nullable=True)
    created_at: Mapped[datetime] = _created_at()
    completed_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), nullable=True
    )

    # --- relationships -----------------------------------------------------
    subclaims: Mapped[list["Subclaim"]] = orm_relationship(
        back_populates="claim",
        cascade="all, delete-orphan",
        passive_deletes=True,
        order_by="Subclaim.ordinal",
    )
    sources: Mapped[list["Source"]] = orm_relationship(
        back_populates="claim",
        cascade="all, delete-orphan",
        passive_deletes=True,
    )
    runs: Mapped[list["Run"]] = orm_relationship(
        back_populates="claim",
        cascade="all, delete-orphan",
        passive_deletes=True,
        order_by="Run.started_at",
    )
    verdict: Mapped["Verdict | None"] = orm_relationship(
        back_populates="claim",
        cascade="all, delete-orphan",
        passive_deletes=True,
        uselist=False,
    )

    def __repr__(self) -> str:  # pragma: no cover - debugging aid
        return f"<Claim id={self.id} status={self.status!r}>"


