class EvidenceLink(Base):
    """A judged relationship between one passage and one subclaim.

    This is the core unit of traceability: every verdict the system produces
    reduces to a set of these rows.
    """

    __tablename__ = "evidence_links"
    __table_args__ = (
        CheckConstraint(
            _in_clause("relationship", RELATIONSHIPS),
            name="ck_evidence_relationship",
        ),
        CheckConstraint(
            "relevance_score BETWEEN 0 AND 1", name="ck_evidence_relevance_range"
        ),
        CheckConstraint(
            "evidence_quality_score BETWEEN 0 AND 1",
            name="ck_evidence_quality_range",
        ),
        CheckConstraint(
            "stance_confidence BETWEEN 0 AND 1", name="ck_evidence_stance_range"
        ),
        CheckConstraint(
            _in_clause("quote_validation", QUOTE_VALIDATION_STATES),
            name="ck_evidence_quote_validation",
        ),
        UniqueConstraint(
            "subclaim_id", "passage_id", name="uq_evidence_subclaim_passage"
        ),
        Index("ix_evidence_subclaim", "subclaim_id"),
        Index("ix_evidence_passage", "passage_id"),
        Index("ix_evidence_relationship", "relationship"),
    )

    id: Mapped[uuid.UUID] = _uuid_pk()
    subclaim_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("subclaims.id", ondelete="CASCADE"),
        nullable=False,
    )
    passage_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("passages.id", ondelete="CASCADE"),
        nullable=False,
    )
    relationship: Mapped[str] = mapped_column(Text, nullable=False)
    relevance_score: Mapped[Decimal] = mapped_column(Numeric(4, 3), nullable=False)
    evidence_quality_score: Mapped[Decimal] = mapped_column(
        Numeric(4, 3), nullable=False
    )
    stance_confidence: Mapped[Decimal] = mapped_column(Numeric(4, 3), nullable=False)
    quote: Mapped[str] = mapped_column(Text, nullable=False, server_default=sa_text("''"))
    rationale: Mapped[str] = mapped_column(
        Text, nullable=False, server_default=sa_text("''")
    )
    model: Mapped[str | None] = mapped_column(Text, nullable=True)
    prompt_version: Mapped[str | None] = mapped_column(Text, nullable=True)
    quote_validation: Mapped[str] = mapped_column(
        Text, nullable=False, server_default=sa_text("'passed'")
    )
    created_at: Mapped[datetime] = _created_at()

    # --- relationships -----------------------------------------------------
    subclaim: Mapped["Subclaim"] = orm_relationship(back_populates="evidence_links")
    passage: Mapped["Passage"] = orm_relationship(back_populates="evidence_links")

    def __repr__(self) -> str:  # pragma: no cover - debugging aid
        return f"<EvidenceLink id={self.id} relationship={self.relationship}>"


