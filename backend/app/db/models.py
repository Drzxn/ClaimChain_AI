class Verdict(Base):
    """Deterministic overall verdict for a claim. One row per claim.

    Produced by ``agg-1.0.0`` from stored ``evidence_links`` and
    ``subclaim_verdicts``. Never written directly by an LLM.
    """

    __tablename__ = "verdicts"
    __table_args__ = (
        CheckConstraint(
            _in_clause("verdict", OVERALL_VERDICTS), name="ck_verdicts_verdict"
        ),
        CheckConstraint("score BETWEEN -1 AND 1", name="ck_verdicts_score"),
        CheckConstraint("coverage BETWEEN 0 AND 1", name="ck_verdicts_coverage"),
        CheckConstraint(
            "contradicted_weight_ratio BETWEEN 0 AND 1",
            name="ck_verdicts_contradicted_ratio",
        ),
    )

    id: Mapped[uuid.UUID] = _uuid_pk()
    claim_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("claims.id", ondelete="CASCADE"),
        nullable=False,
        unique=True,
    )
    verdict: Mapped[str] = mapped_column(Text, nullable=False)
    score: Mapped[Decimal] = mapped_column(Numeric(5, 4), nullable=False)
    coverage: Mapped[Decimal] = mapped_column(Numeric(5, 4), nullable=False)
    contradicted_weight_ratio: Mapped[Decimal] = mapped_column(
        Numeric(5, 4), nullable=False, server_default=sa_text("0")
    )
    subclaim_counts: Mapped[dict[str, Any]] = mapped_column(
        JSONB, nullable=False, server_default=sa_text("'{}'::jsonb")
    )
    summary: Mapped[str | None] = mapped_column(Text, nullable=True)
    limitations: Mapped[list[Any]] = mapped_column(
        JSONB, nullable=False, server_default=sa_text("'[]'::jsonb")
    )
    aggregation_version: Mapped[str] = mapped_column(Text, nullable=False)
    computed_at: Mapped[datetime] = _created_at()
    report_generated_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), nullable=True
    )

    # --- relationships -----------------------------------------------------
    claim: Mapped["Claim"] = orm_relationship(back_populates="verdict")

    def __repr__(self) -> str:  # pragma: no cover - debugging aid
        return f"<Verdict id={self.id} verdict={self.verdict}>"


