class Run(Base):
    """One execution attempt of one pipeline stage for one claim.

    ``stage`` holds the conceptual stage number (1-6). Runtime order is
    1 -> 2 -> 3 -> 5 -> 4 -> 6; ordering is recorded by ``started_at``, not by
    the stage number.
    """

    __tablename__ = "runs"
    __table_args__ = (
        CheckConstraint("stage BETWEEN 1 AND 6", name="ck_runs_stage_range"),
        CheckConstraint("attempt >= 1", name="ck_runs_attempt"),
        CheckConstraint(_in_clause("status", RUN_STATUSES), name="ck_runs_status"),
        UniqueConstraint(
            "claim_id", "stage", "attempt", name="uq_runs_claim_stage_attempt"
        ),
        Index("ix_runs_claim", "claim_id", "started_at"),
    )

    id: Mapped[uuid.UUID] = _uuid_pk()
    claim_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("claims.id", ondelete="CASCADE"),
        nullable=False,
    )
    stage: Mapped[int] = mapped_column(Integer, nullable=False)
    attempt: Mapped[int] = mapped_column(
        Integer, nullable=False, server_default=sa_text("1")
    )
    status: Mapped[str] = mapped_column(Text, nullable=False)
    started_at: Mapped[datetime] = _created_at()
    finished_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), nullable=True
    )
    error: Mapped[str | None] = mapped_column(Text, nullable=True)
    tokens_in: Mapped[int] = mapped_column(
        Integer, nullable=False, server_default=sa_text("0")
    )
    tokens_out: Mapped[int] = mapped_column(
        Integer, nullable=False, server_default=sa_text("0")
    )
    cost_usd: Mapped[Decimal] = mapped_column(
        Numeric(10, 6), nullable=False, server_default=sa_text("0")
    )
    cache_hit: Mapped[bool] = mapped_column(
        Boolean, nullable=False, server_default=sa_text("false")
    )

    # --- relationships -----------------------------------------------------
    claim: Mapped["Claim"] = orm_relationship(back_populates="runs")

    def __repr__(self) -> str:  # pragma: no cover - debugging aid
        return f"<Run id={self.id} stage={self.stage} status={self.status!r}>"


