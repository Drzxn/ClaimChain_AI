class Subclaim(Base):
    """One atomic, independently checkable proposition from a claim."""

    __tablename__ = "subclaims"
    __table_args__ = (
        CheckConstraint("ordinal >= 1", name="ck_subclaims_ordinal"),
        CheckConstraint(
            "char_length(text) BETWEEN 1 AND 300", name="ck_subclaims_text_length"
        ),
        CheckConstraint(
            _in_clause("claim_type", CLAIM_TYPES), name="ck_subclaims_claim_type"
        ),
        CheckConstraint("weight > 0", name="ck_subclaims_weight_positive"),
        UniqueConstraint("claim_id", "ordinal", name="uq_subclaims_claim_ordinal"),
        Index("ix_subclaims_claim", "claim_id"),
    )

    id: Mapped[uuid.UUID] = _uuid_pk()
    claim_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("claims.id", ondelete="CASCADE"),
        nullable=False,
    )
    ordinal: Mapped[int] = mapped_column(Integer, nullable=False)
    text: Mapped[str] = mapped_column(Text, nullable=False)
    claim_type: Mapped[str] = mapped_column(Text, nullable=False)
    # Fixed at 1.0 in v1; the column exists so weights are not hard-coded.
    weight: Mapped[Decimal] = mapped_column(
        Numeric(4, 2), nullable=False, server_default=sa_text("1.0")
    )
    decomposition_note: Mapped[str | None] = mapped_column(Text, nullable=True)

    # --- relationships -----------------------------------------------------
    claim: Mapped["Claim"] = orm_relationship(back_populates="subclaims")
    evidence_links: Mapped[list["EvidenceLink"]] = orm_relationship(
        back_populates="subclaim",
        cascade="all, delete-orphan",
        passive_deletes=True,
    )
    verdict: Mapped["SubclaimVerdict | None"] = orm_relationship(
        back_populates="subclaim",
        cascade="all, delete-orphan",
        passive_deletes=True,
        uselist=False,
    )

    def __repr__(self) -> str:  # pragma: no cover - debugging aid
        return f"<Subclaim id={self.id} ordinal={self.ordinal}>"


