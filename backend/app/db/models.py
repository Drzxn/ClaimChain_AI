class Source(Base):
    """A retrieved web source, with its quality assessment.

    Source quality (``authority_score``, ``recency_score``) lives here, on the
    source. It is deliberately separate from the claim relationship, which
    lives on ``EvidenceLink``. A prestigious source can be irrelevant; a weak
    source can be directly on point. Collapsing the two loses that.
    """

    __tablename__ = "sources"
    __table_args__ = (
        CheckConstraint(
            _in_clause("source_type", SOURCE_TYPES), name="ck_sources_source_type"
        ),
        CheckConstraint(
            "authority_score BETWEEN 0 AND 1", name="ck_sources_authority_range"
        ),
        CheckConstraint(
            "recency_score BETWEEN 0 AND 1", name="ck_sources_recency_range"
        ),
        UniqueConstraint("claim_id", "url_hash", name="uq_sources_claim_url"),
        Index("ix_sources_claim", "claim_id"),
        Index("ix_sources_content_hash", "content_hash"),
    )

    id: Mapped[uuid.UUID] = _uuid_pk()
    claim_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("claims.id", ondelete="CASCADE"),
        nullable=False,
    )
    url: Mapped[str] = mapped_column(Text, nullable=False)
    url_hash: Mapped[str] = mapped_column(String(64), nullable=False)
    domain: Mapped[str] = mapped_column(Text, nullable=False)
    title: Mapped[str | None] = mapped_column(Text, nullable=True)
    publisher: Mapped[str | None] = mapped_column(Text, nullable=True)
    source_type: Mapped[str] = mapped_column(
        Text, nullable=False, server_default=sa_text("'unknown'")
    )
    cites_primary_sources: Mapped[bool | None] = mapped_column(Boolean, nullable=True)
    published_at: Mapped[date | None] = mapped_column(Date, nullable=True)
    retrieved_at: Mapped[datetime] = _created_at()
    content_hash: Mapped[str | None] = mapped_column(String(64), nullable=True)
    # Self-reference: a duplicate points at the source it duplicates. SET NULL
    # so deleting the canonical row does not delete the duplicate's history.
    duplicate_of: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("sources.id", ondelete="SET NULL"),
        nullable=True,
    )
    authority_score: Mapped[Decimal | None] = mapped_column(
        Numeric(4, 3), nullable=True
    )
    recency_score: Mapped[Decimal | None] = mapped_column(Numeric(4, 3), nullable=True)
    assessment_rationale: Mapped[str | None] = mapped_column(Text, nullable=True)
    assessed_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), nullable=True
    )

    # --- relationships -----------------------------------------------------
    claim: Mapped["Claim"] = orm_relationship(back_populates="sources")
    passages: Mapped[list["Passage"]] = orm_relationship(
        back_populates="source",
        cascade="all, delete-orphan",
        passive_deletes=True,
        order_by="Passage.chunk_index",
    )

    def __repr__(self) -> str:  # pragma: no cover - debugging aid
        return f"<Source id={self.id} domain={self.domain!r}>"


